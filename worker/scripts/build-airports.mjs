// Builds airports.sql (a D1 table of airports with IATA codes) from the open
// mwgg/Airports database (https://github.com/mwgg/Airports, MIT).
// Usage: node scripts/build-airports.mjs path/to/airports.json
//        npx wrangler d1 execute flight-tracker --remote --file=airports.sql
import { readFileSync, writeFileSync } from "node:fs";
const src = JSON.parse(readFileSync(process.argv[2], "utf8"));
const q = (s) => (s == null || s === "" ? "null" : `'${String(s).replace(/'/g, "''")}'`);
const rows = [];
for (const a of Object.values(src)) {
  if (!/^[A-Z]{3}$/.test(a.iata ?? "") || !a.tz) continue;
  rows.push(`(${q(a.iata)},${q(a.icao)},${q(a.name)},${q(a.city)},${q(a.country)},${q(a.tz)},${(+a.lat).toFixed(4)},${(+a.lon).toFixed(4)})`);
}
let sql = `-- Generated by scripts/build-airports.mjs. Safe to run again.
create table if not exists airports (
  iata text primary key, icao text, name text, city text, country text, tz text not null, lat real, lon real
);
delete from airports;
`;
for (let i = 0; i < rows.length; i += 400) sql += `insert into airports values ${rows.slice(i, i + 400).join(",\n")};\n`;
writeFileSync(new URL("../airports.sql", import.meta.url), sql);
console.log(rows.length, "airports");
